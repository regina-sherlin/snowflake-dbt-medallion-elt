
-- 1. CREATE VIRTUAL WAREHOUSE & DATABASE
CREATE WAREHOUSE IF NOT EXISTS ELT_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60 
    AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS SEISMIC_ELT_DB;
USE DATABASE SEISMIC_ELT_DB;


-- 2. CREATE MEDALLION & METADATA SCHEMAS 
CREATE SCHEMA IF NOT EXISTS META;
CREATE SCHEMA IF NOT EXISTS BRONZE;
CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS GOLD;


-- 3. CREATE WATERMARK STATE TABLE IN META 
CREATE TABLE IF NOT EXISTS META.PIPELINE_WATERMARKS (
    PIPELINE_NAME VARCHAR(100) PRIMARY KEY,
    LAST_RUN_TIMESTAMP TIMESTAMP_NTZ NOT NULL,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- 4. CREATE RAW LANDING TABLE IN BRONZE 
CREATE TABLE IF NOT EXISTS BRONZE.RAW_EARTHQUAKE_EVENTS(
    BATCH_ID VARCHAR(50) NOT NULL,
    SOURCE_EVENT_ID VARCHAR(100) NOT NULL,
    RAW_PAYLOAD VARIANT NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


